#!/usr/bin/env python3
"""Extract exact BYOB output colors from pinned Switch v3.0.1 original bundles."""
import argparse
import hashlib
import importlib.util
import struct as s
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG_SHA = '9888453f39d5e1f509f324d6c8a12a2384b9bb3edd58b8c83bfb5a91b8165f55'
DEFINITIONS_SHA = '660aba36ab6da5964180fe0d474696fc22dd806b2f5b19ce601222cb5a631afa'
CONFIG_CAB = 'CAB-5f79c218689053d862a6ced51baba3e0'
DEFINITIONS_CAB = 'CAB-191652df9468c684714b3b89a22974ec'
CONFIG_PATH_ID = 8463800613119872860
OUTPUT_SHA = '76304a597cd7328c8696e580aa4644f0b638e8c9ff3e5be3f9ab8b6c85501937'

def require(ok, reason):
    if not ok:
        raise ValueError(reason)

def read_cab(path, sha, cab):
    source = path.read_bytes()
    require(hashlib.sha256(source).hexdigest() == sha, 'unexpected original bundle')
    spec = importlib.util.spec_from_file_location('unityfs_audit', ROOT / 'scripts/unityfs-audit.py')
    audit = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(audit)
    return dict(audit.extract_nodes(source)[1])[cab]

def cstr(b,p):
    end=b.index(0,p)
    return b[p:end].decode(),end+1

def align(n): return (n+3)&~3

def serialized_objects(b):
    require(s.unpack_from('>I',b,8)[0]==22 and b[16]==0,'unexpected SerializedFile')
    offset=s.unpack_from('>Q',b,32)[0]
    _,p=cstr(b,48);p+=4
    require(b[p]==1,'missing type tree')
    p+=1
    n=s.unpack_from('<I',b,p)[0];p+=4;types=[]
    for _ in range(n):
        cls=s.unpack_from('<i',b,p)[0]
        p+=7+(16 if cls==114 or cls<0 else 0)+16
        nn,ss=s.unpack_from('<II',b,p);p+=8
        buf=b[p+32*nn:p+32*nn+ss]
        def name(i):
            return 'common:'+str(i&0x7fffffff) if i&0x80000000 else cstr(buf,i)[0]
        nodes=[]
        for j in range(nn):
            _,lev,_,ty,na,sz,_,flags,_=s.unpack_from('<HBBIIiiIQ',b,p+32*j)
            nodes.append((lev,name(ty),name(na),sz,flags))
        p+=32*nn+ss
        dep=s.unpack_from('<I',b,p)[0];p+=4+4*dep
        types.append((cls,nodes))
    n=s.unpack_from('<I',b,p)[0];p=align(p+4);objects={}
    for _ in range(n):
        id,start,size,t=s.unpack_from('<qqIi',b,p);p+=24
        require(id not in objects and 0<=t<len(types) and 0<=offset+start<=offset+start+size<=len(b),'bad object entry')
        objects[id]=(offset+start,size,t)
    scripts=s.unpack_from('<I',b,p)[0];p+=4+12*scripts
    count=s.unpack_from('<I',b,p)[0];p+=4
    externals=[]
    for _ in range(count):
        _,p=cstr(b,p);p+=20
        path,p=cstr(b,p);externals.append(path)
    return types,objects,externals

def extract(config,definitions):
    b=read_cab(config,CONFIG_SHA,CONFIG_CAB)
    d=read_cab(definitions,DEFINITIONS_SHA,DEFINITIONS_CAB)
    ct,co,ce=serialized_objects(b);dt,do,_=serialized_objects(d)
    require(ce[1]=='archive:/'+DEFINITIONS_CAB+'/'+DEFINITIONS_CAB,'flower reference CAB mismatch')
    start,size,t=co[CONFIG_PATH_ID];data=b[start:start+size]
    require(hashlib.sha256(data).hexdigest()=='f1ab01c368ec48c09153ca7c18dc4b275eb4b1127b2813241cd61850ffebdc02','config object fingerprint')
    require(ct[t][0]==114 and all(x in [n[2] for n in ct[t][1]] for x in ('PaletteColorMap','BaseColor','BlackAdditiveOutputs','WhiteAdditiveOutputs')),'wrong config type')
    n=s.unpack_from('<I',data,28)[0]
    require(data[32:32+n]==b'Default.CustomPaletteConfig','config name mismatch')
    p=align(32+n);count=s.unpack_from('<I',data,p)[0];p+=4
    require(count==29,'wrong flower key count')
    indices=[]
    for _ in range(count):
        file_id,path_id=s.unpack_from('<iq',data,p);p+=12
        require(file_id==2,'wrong flower file')
        a,z,typ=do[path_id];obj=d[a:a+z]
        require(dt[typ][0]==114 and dt[typ][1][16][2]=='ColorIndex','wrong flower type')
        name_len=s.unpack_from('<I',obj,28)[0];q=align(32+name_len)
        guid_len=s.unpack_from('<I',obj,q)[0];q=align(q+4+guid_len)
        require(guid_len==32,'wrong flower GUID length')
        indices.append(s.unpack_from('<i',obj,q)[0])
    require(indices==list(range(1,30)),'unexpected flower index order')
    require(s.unpack_from('<I',data,p)[0]==count,'wrong value count');p+=4
    rows=[]
    for _ in indices:
        row=data[p:p+16];p+=16
        for _ in range(2):
            require(s.unpack_from('<4I',data,p)==(2,1,2,2),'unexpected additive keys')
            p+=16;row+=data[p:p+32];p+=32
        rows.append(row)
    require(p==len(data) and len(rows)==29 and all(len(row)==80 for row in rows),'config payload boundary')
    require(hashlib.sha256(b''.join(rows)).hexdigest()==OUTPUT_SHA,'output fingerprint')
    return rows

def render(rows):
    header="// Generated by scripts/extract-inventory-palette-colors.py from pinned Switch v3.0.1 originals.\n// Indexed by FlowerColorDefinition.ColorIndex - 1; ordered base, black 1/2, white 1/2.\n// Exact binary32 words. Definition evidence only, not player ownership/edit permission.\n"
    lines=[]
    for row in rows:
        colors=['['+','.join(f'0x{word:08x}' for word in s.unpack_from('<4I',row,i))+']' for i in range(0,80,16)]
        lines.append(' ['+','.join(colors)+'],')
    return header+'pub(super) const PALETTE_COLORS:[[[u32;4];5];29]=[\n'+'\n'.join(lines)+'\n];\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('config',type=Path)
    parser.add_argument('definitions',type=Path)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    content=render(extract(args.config,args.definitions))
    path=ROOT/'core/src/inventory_palette_source_data.rs'
    if args.check:
        require(path.read_text()==content,'source table differs')
    else:
        path.write_text(content,encoding='utf-8')
    print('Verified 29 native flower keys, 145 output RGBA values; no save changes.')
