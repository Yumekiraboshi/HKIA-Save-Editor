import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
test('icon update pipeline resumes only unchanged verified checkpoints and never commits interrupted output',()=>{
 const script=fileURLToPath(new URL('../scripts/update-icon-release.py',import.meta.url));
 const result=spawnSync(process.env.PYTHON??'python3',[script,'--self-test'],{encoding:'utf8'});
 assert.equal(result.status,0,result.stderr??String(result.error));
 assert.match(result.stdout,/HKIA_ICON_UPDATE_PIPELINE_SELF_TEST_OK/);
});
